import { Request, Response } from 'express';
import { prisma } from '../../index';

const VALID_TRANSITIONS: Record<string, string[]> = {
  'CREATED': ['SUBMITTED', 'CANCELLED'],
  'SUBMITTED': ['ACCEPTED', 'REJECTED'],
  'ACCEPTED': ['SCHEDULED'],
  'SCHEDULED': ['PATIENT_ARRIVED', 'CANCELLED'],
  'PATIENT_ARRIVED': ['IN_CONSULTATION'],
  'IN_CONSULTATION': ['DIAGNOSTICS_PENDING', 'TREATMENT', 'COUNTER_REFERRED'],
  'DIAGNOSTICS_PENDING': ['TREATMENT', 'COUNTER_REFERRED'],
  'TREATMENT': ['COUNTER_REFERRED'],
  'COUNTER_REFERRED': ['FOLLOW_UP_REQUIRED', 'COMPLETED'],
  'FOLLOW_UP_REQUIRED': ['COMPLETED']
};

export const createReferral = async (req: Request, res: Response) => {
  try {
    const { patientId, originId, destinationId, urgency, reason } = req.body;

    if (!patientId || !destinationId) {
      return res.status(400).json({ error: 'Bad Request', message: 'patientId and destinationId are required' });
    }

    const patient = await prisma.patient.findUnique({ where: { id: patientId } });
    if (!patient) {
      return res.status(404).json({ error: 'Not Found', message: 'Patient not found' });
    }

    const destFacility = await prisma.facility.findUnique({ where: { id: destinationId } });
    if (!destFacility) {
      return res.status(404).json({ error: 'Not Found', message: 'Destination facility not found' });
    }

    // Default origin to first facility if originId is missing or invalid
    let finalOriginId = originId;
    if (!finalOriginId) {
      const defaultFac = await prisma.facility.findFirst();
      finalOriginId = defaultFac?.id || destinationId;
    }

    const rawUrgency = String(urgency || 'ROUTINE').toUpperCase().trim();
    const validUrgencies = ['ROUTINE', 'PRIORITY', 'URGENT', 'EMERGENCY'];
    const finalUrgency = validUrgencies.includes(rawUrgency) ? rawUrgency : 'ROUTINE';
    const cleanReason = String(reason || 'Clinical referral').trim().slice(0, 500);

    const referral = await prisma.$transaction(async (tx) => {
      const ref = await tx.referral.create({
        data: {
          patientId,
          originId: finalOriginId,
          destinationId,
          urgency: finalUrgency,
          reason: cleanReason,
          status: 'SUBMITTED'
        }
      });

      await tx.referralEvent.create({
        data: {
          referralId: ref.id,
          statusFrom: 'CREATED',
          statusTo: 'SUBMITTED',
          notes: 'Referral generated by frontline health worker'
        }
      });

      return ref;
    });

    res.status(201).json(referral);
  } catch (error) {
    console.error('Error creating referral:', error);
    res.status(500).json({ error: 'Internal Server Error' });
  }
};

export const updateReferralStatus = async (req: Request, res: Response) => {
  try {
    const { id } = req.params;
    const { newStatus, notes } = req.body;

    if (!id || typeof id !== 'string') {
      return res.status(400).json({ error: 'Bad Request', message: 'Referral ID is required' });
    }

    if (!newStatus || typeof newStatus !== 'string') {
      return res.status(400).json({ error: 'Bad Request', message: 'newStatus is required' });
    }

    const referral = await prisma.referral.findUnique({ where: { id } });
    if (!referral) return res.status(404).json({ error: 'Not Found', message: 'Referral not found' });

    const currentStatus = referral.status;
    
    // 24. REFERRAL STATE MACHINE: Reject invalid transitions
    if (!VALID_TRANSITIONS[currentStatus]?.includes(newStatus)) {
      return res.status(400).json({ error: 'Invalid Transition', message: `Cannot transition from ${currentStatus} to ${newStatus}` });
    }

    const cleanNotes = notes ? String(notes).trim().slice(0, 500) : undefined;

    const updated = await prisma.$transaction(async (tx) => {
      // 24. Record every transition in ReferralEvent
      await tx.referralEvent.create({
        data: {
          referralId: id,
          statusFrom: currentStatus,
          statusTo: newStatus,
          notes: cleanNotes
        }
      });

      const updatedRef = await tx.referral.update({
        where: { id },
        data: { status: newStatus },
        include: {
          patient: true,
          origin: true,
          destination: true,
          events: { orderBy: { createdAt: 'desc' } }
        }
      });

      return updatedRef;
    });

    res.json(updated);
  } catch (error) {
    res.status(500).json({ error: 'Internal Server Error' });
  }
};

export const getReferrals = async (req: Request, res: Response) => {
  try {
    const { status, destinationId } = req.query;
    const where: any = {};
    if (status && typeof status === 'string') {
      where.status = status;
    }
    if (destinationId && typeof destinationId === 'string') {
      where.destinationId = destinationId;
    }
    const referrals = await prisma.referral.findMany({
      where,
      include: {
        patient: true,
        origin: true,
        destination: true,
        events: { orderBy: { createdAt: 'desc' }, take: 1 }
      },
      take: 50
    });
    res.json(referrals);
  } catch (error) {
    console.error('Error fetching referrals:', error);
    res.status(500).json({ error: 'Internal Server Error' });
  }
};

